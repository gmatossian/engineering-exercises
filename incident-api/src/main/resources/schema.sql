/*
Enum-like constraints
---------------------
Example: CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH'))

- Purpose: restrict the column to the listed values.
- Enforcement: reject inserts/updates with other values.
- Nulls: NOT NULL handles these separately.
- Maintenance: keep the list aligned with the Java enum; changes to Java constants do not update this constraint.
*/

CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    site_id VARCHAR(100) NOT NULL,
    type VARCHAR(100) NOT NULL,
    severity VARCHAR(10) NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
    occurred_at TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    description VARCHAR(4000) NOT NULL
);

CREATE INDEX incidents_occurrence_order ON incidents (occurred_at DESC, id DESC);

/*
ON DELETE CASCADE
-----------------
- Deleting an incident also deletes its activities, enforced by the database.
- Deleting an activity does not delete its incident.
*/

CREATE TABLE incident_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    action VARCHAR(100) NOT NULL,
    actor_id VARCHAR(100) NOT NULL,
    occurred_at TIMESTAMP(9) WITH TIME ZONE NOT NULL
);

CREATE INDEX incident_activities_lookup ON incident_activities (incident_id, occurred_at, id);
